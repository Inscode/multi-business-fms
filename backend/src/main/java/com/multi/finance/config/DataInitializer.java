    private ReturnProduct product(BusinessType business, String name, String price) {
        return ReturnProduct.builder()
                .business(business)
                .name(name)
                .unitPrice(new BigDecimal(price))
                .active(true)
                .createdAt(LocalDateTime.now())
                .build();
    }

    private void createUserIfNotExists(
            String username,
            String fullName,
            UserRole role,
            String password) {

        if (userRepository.findByUsername(username).isPresent()) {
            log.info("[Init] User '{}' already exists, skipping.", username);
            return;
        }

        userRepository.save(User.builder()
                .username(username)
                .passwordHash(passwordEncoder.encode(password))
                .fullName(fullName)
                .role(role)
                .active(true)
                .createdAt(LocalDateTime.now())
                .updatedAt(LocalDateTime.now())
                .build());

        log.info("[Init] User '{}' created with role {}.", username, role);
    }
